// inferAgainstNodeModules infers src against a tree holding files. The tree is both the
// stdlib directory and the package directory, so a `node_modules/...` key declares an
// npm package beside the pseudo-packages. It returns the run and the tree's root.
func inferAgainstNodeModules(t *testing.T, src string, files map[string]string) (*ModuleResult, string) {
	t.Helper()
	dir := seedStdlib(t, withPreludeClasses(files))
	return InferModuleAgainstStdlib(parseModule(t, src), dir, Options{PackageDir: dir}), dir
}

// TestNodeModulesImportResolves covers a bare import whose types a `node_modules`
// package declares. Each case renders the value bindings the import makes reachable.
func TestNodeModulesImportResolves(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		files map[string]string
		src   string
		want  map[string]string
	}{
		{
			name: "a package that ships its own types",
			files: map[string]string{
				"node_modules/plain/package.json": `{"types": "index.d.ts"}`,
				"node_modules/plain/index.d.ts": `export declare function add(a: number, b: number): number;
export declare const version: string;`,
			},
			src: `import "plain" as p
val n = p.add(1, 2)
val v = p.version`,
			want: map[string]string{"n": "number", "v": "string"},
		},
		{
			name: "a package whose types are in @types",
			files: map[string]string{
				"node_modules/@types/typed/index.d.ts": `export declare const answer: number;`,
			},
			src: `import "typed" as typed
val a = typed.answer`,
			want: map[string]string{"a": "number"},
		},
		{
			name: "a package declared in a declare module block",
			files: map[string]string{
				"node_modules/named/index.d.ts": `declare module "named" {
    export const label: string;
}`,
			},
			src: `import "named" as named
val l = named.label`,
			want: map[string]string{"l": "string"},
		},
		{
			name: "a subpath beside the package's own entry point",
			files: map[string]string{
				"node_modules/split/index.d.ts":    `export declare const main: string;`,
				"node_modules/split/fp/index.d.ts": `export declare const fp: number;`,
			},
			src: `import "split" as split
import "split/fp" as fp
val m = split.main
val f = fp.fp`,
			want: map[string]string{"m": "string", "f": "number"},
		},
		{
			name: "a subpath that names a file",
			files: map[string]string{
				"node_modules/files/index.d.ts":   `export declare const main: string;`,
				"node_modules/files/extra.d.ts":   `export declare const extra: boolean;`,
				"node_modules/files/package.json": `{"types": "index.d.ts"}`,
			},
			src: `import "files/extra" as extra
val e = extra.extra`,
			want: map[string]string{"e": "boolean"},
		},
		{
			name: "a scoped package whose types are in @types",
			files: map[string]string{
				"node_modules/@types/scope__pkg/index.d.ts": `export declare const scoped: number;`,
			},
			src: `import "@scope/pkg" as pkg
val s = pkg.scoped`,
			want: map[string]string{"s": "number"},
		},
		{
			name: "a package that names a type from the ambient scope",
			files: map[string]string{
				"std/json.esc":                   `export declare type JsonTag = string`,
				"node_modules/tagged/index.d.ts": `export declare const tag: JsonTag;`,
			},
			src: `import "tagged" as tagged
val t = tagged.tag`,
			want: map[string]string{"t": "JsonTag"},
		},
		{
			name: "a pseudo-package beside an npm package",
			files: map[string]string{
				"std/math.esc":                  `export val PI: number = 3`,
				"node_modules/plain/index.d.ts": `export declare const version: string;`,
			},
			src: `import "std:math"
import "plain" as p
val x = math.PI
val v = p.version`,
			want: map[string]string{"x": "number", "v": "string"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			res, _ := inferAgainstNodeModules(t, test.src, test.files)
			require.Empty(t, errorMessagesOf(res.Errors))
			for name, want := range test.want {
				require.Equal(t, want, soltype.Print(inferredValueType(t, res.Scope, name)), "value %q", name)
			}
		})
	}
}

// TestNodeModulesImportResolvesReadonlyTwins covers each TypeScript spelling of a
// readonly collection in an npm package's types. Each one resolves to the
// immutable form of the matching class in the committed tree, which declares no
// `ReadonlyArray`, `ReadonlyMap` or `ReadonlySet`.
func TestNodeModulesImportResolvesReadonlyTwins(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		decl string
		want string
	}{
		{name: "the readonly array shorthand", decl: "readonly number[]", want: "Array<number>"},
		{name: "ReadonlyArray", decl: "ReadonlyArray<number>", want: "Array<number>"},
		{name: "ReadonlyMap", decl: "ReadonlyMap<string, number>", want: "Map<string, number>"},
		{name: "ReadonlySet", decl: "ReadonlySet<number>", want: "Set<number>"},
		{name: "a nested ReadonlyArray", decl: "Array<ReadonlyArray<number>>", want: "Array<Array<number>>"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			res, _ := inferAgainstNodeModules(t, "import \"twins\" as twins\nval x = twins.x", map[string]string{
				"std/map.esc":                   "export declare class Map<K, V> { get(&self, key: K) -> V | undefined }",
				"std/set.esc":                   "export declare class Set<T> { has(&self, value: T) -> boolean }",
				"node_modules/twins/index.d.ts": "export declare const x: " + test.decl + ";",
			})
			require.Empty(t, errorMessagesOf(res.Errors))
			require.Equal(t, test.want, soltype.Print(inferredValueType(t, res.Scope, "x")))
		})
	}
}

// TestNodeModulesImportRejectsMutatingAReadonlyArray asserts that a `readonly T[]` in an
// npm package's types rejects a call to a `&mut self` method.
func TestNodeModulesImportRejectsMutatingAReadonlyArray(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, map[string]string{
		"std/prelude.esc": `export declare class Array<T> { push(&mut self, value: T) -> number }
export declare class Promise<T, E = never> { then<U>(&self, f: fn (v: T) -> U) -> Promise<U, E> }`,
		"node_modules/twins/index.d.ts": "export declare const x: readonly number[];",
	})
	src := "import \"twins\" as twins\nval n = twins.x.push(1)"
	res := InferModuleAgainstStdlib(parseModule(t, src), dir, Options{PackageDir: dir})
	require.Equal(t,
		[]string{"cannot constrain immutable Array<number> <: mutable Array<number>"},
		errorMessagesOf(res.Errors))
}

