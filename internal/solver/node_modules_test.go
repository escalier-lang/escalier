// TestNodeModulesImportReportsAnUnloadableExport covers an export statement that fails
// the package's load. Each case wants the one error the import reports. want receives
// the directory holding the package's files.
func TestNodeModulesImportReportsAnUnloadableExport(t *testing.T) {
	t.Parallel()

	const otherPackage = "%s exports names from %q, and exporting names from another package is not supported"
	tests := []struct {
		name  string
		files map[string]string
		want  func(pkg string) string
	}{
		{
			name: "an export from another package",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export { a } from "other";`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf(otherPackage, filepath.Join(pkg, "index.d.ts"), "other")
			},
		},
		{
			name: "an export * from another package",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export * from "other";`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf(otherPackage, filepath.Join(pkg, "index.d.ts"), "other")
			},
		},
		{
			name: "an export of a name imported from another package",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `import { a } from "other";
export { a };`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf(otherPackage, filepath.Join(pkg, "index.d.ts"), "other")
			},
		},
		{
			name: "a specifier that names no file",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export * from "./missing";`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports names from %q, which names no .d.ts file",
					filepath.Join(pkg, "index.d.ts"), "./missing")
			},
		},
		{
			name: "a name the other file does not export",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export { absent } from "./other";`,
				"node_modules/pkg/other.d.ts": `export declare const a: number;`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports %q from %s, which does not export it",
					filepath.Join(pkg, "index.d.ts"), "absent", filepath.Join(pkg, "other.d.ts"))
			},
		},
		{
			name: "a local export of a name the file does not bind",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export { absent };`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports %q, which it neither declares nor imports",
					filepath.Join(pkg, "index.d.ts"), "absent")
			},
		},
		{
			name: "a local export of a namespace import",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `import * as ns from "./other";
export { ns };`,
				"node_modules/pkg/other.d.ts": `export declare const a: number;`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports %q, which a default or namespace import binds, and exporting one is not supported",
					filepath.Join(pkg, "index.d.ts"), "ns")
			},
		},
		{
			name: "an export * as a namespace",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export * as ns from "./other";`,
				"node_modules/pkg/other.d.ts": `export declare const a: number;`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports %s as %q, and exporting a file as a namespace is not supported",
					filepath.Join(pkg, "index.d.ts"), "./other", "ns")
			},
		},
		{
			name: "two files that declare the same name",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `declare const shared: string;
export * from "./other";`,
				"node_modules/pkg/other.d.ts": `export declare const shared: number;`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s and %s both declare %q, and a package's files cannot share a top-level name",
					filepath.Join(pkg, "index.d.ts"), filepath.Join(pkg, "other.d.ts"), "shared")
			},
		},
		{
			name: "a renamed export whose name another file declares",
			files: map[string]string{
				"node_modules/pkg/index.d.ts": `export { a as b } from "./other";
export * from "./more";`,
				"node_modules/pkg/other.d.ts": `export declare const a: number;`,
				"node_modules/pkg/more.d.ts":  `export declare const b: number;`,
			},
			want: func(pkg string) string {
				return fmt.Sprintf("%s exports %q, which %s also declares, and a package's files cannot share a top-level name",
					filepath.Join(pkg, "index.d.ts"), "b", filepath.Join(pkg, "more.d.ts"))
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			res, dir := inferAgainstNodeModules(t, `import "pkg" as p`, test.files)
			pkg := filepath.Join(dir, "node_modules", "pkg")
			require.Equal(t, []string{fmt.Sprintf("cannot resolve import %q: %s", "pkg", test.want(pkg))},
				errorMessagesOf(res.Errors))
		})
	}
}
