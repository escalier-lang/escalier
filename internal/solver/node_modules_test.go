// TestNodeModulesImportFollowsReferenceDirectives covers a package whose entry point
// reaches other files through `/// <reference … />` directives. The globals those files
// declare are names the package's own declarations read.
func TestNodeModulesImportFollowsReferenceDirectives(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		files map[string]string
		src   string
		want  map[string]string
	}{
		{
			name: "a path directive to a file of globals",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference path="global.d.ts" />
export declare const el: Widget;`,
				"node_modules/ui/global.d.ts": `interface Widget { tag: string }`,
			},
			src:  "import \"ui\" as ui\nval t = ui.el.tag",
			want: map[string]string{"t": "string"},
		},
		{
			name: "path directives that reach each other",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference path="a.d.ts" />
export declare const el: B;`,
				"node_modules/ui/a.d.ts": `/// <reference path="nested/b.d.ts" />
interface A { n: number }`,
				"node_modules/ui/nested/b.d.ts": `/// <reference path="../a.d.ts" />
interface B { a: A }`,
			},
			src:  "import \"ui\" as ui\nval n = ui.el.a.n",
			want: map[string]string{"n": "number"},
		},
		{
			name: "a types directive to another package's globals",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference types="dep" />
export declare const thing: DepThing;`,
				"node_modules/@types/dep/index.d.ts": `interface DepThing { n: number }`,
			},
			src:  "import \"ui\" as ui\nval n = ui.thing.n",
			want: map[string]string{"n": "number"},
		},
		{
			name: "a path directive with no extension",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference path="global" />
export declare const el: Widget;`,
				"node_modules/ui/global.d.ts": `interface Widget { tag: string }`,
			},
			src:  "import \"ui\" as ui\nval t = ui.el.tag",
			want: map[string]string{"t": "string"},
		},
		{
			name: "a types directive that does not resolve",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference types="node" />
export declare const version: string;`,
			},
			src:  "import \"ui\" as ui\nval v = ui.version",
			want: map[string]string{"v": "string"},
		},
		{
			name: "declare module blocks for one package in two files",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference path="more.d.ts" />
declare module "ui" {
    export const a: string;
}`,
				"node_modules/ui/more.d.ts": `declare module "ui" {
    export const b: number;
}`,
			},
			src:  "import \"ui\" as ui\nval a = ui.a\nval b = ui.b",
			want: map[string]string{"a": "string", "b": "number"},
		},
		{
			name: "a lib directive",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference lib="es2015" />
export declare const version: string;`,
			},
			src:  "import \"ui\" as ui\nval v = ui.version",
			want: map[string]string{"v": "string"},
		},
		{
			name: "a declare module block beside a file of globals",
			files: map[string]string{
				"node_modules/ui/index.d.ts": `/// <reference path="global.d.ts" />
declare module "ui" {
    export const el: Widget;
}`,
				"node_modules/ui/global.d.ts": `interface Widget { tag: string }`,
			},
			src:  "import \"ui\" as ui\nval t = ui.el.tag",
			want: map[string]string{"t": "string"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			res, _ := inferAgainstNodeModules(t, test.src, test.files)
			require.Empty(t, errorMessagesOf(res.Errors))
			for name, want := range test.want {
				require.Equal(t, want, soltype.Print(inferredValueType(t, res.Scope, name)), "value %q", name)
			}
		})
	}
}

// TestNodeModulesImportReportsAMissingReference asserts that a path directive naming a
// file that does not exist fails the import, and the error names both files.
func TestNodeModulesImportReportsAMissingReference(t *testing.T) {
	t.Parallel()

	res, dir := inferAgainstNodeModules(t, `import "ui" as ui`, map[string]string{
		"node_modules/ui/index.d.ts": "/// <reference path=\"missing.d.ts\" />\nexport declare const v: string;",
	})
	entry := filepath.Join(dir, "node_modules", "ui", "index.d.ts")
	missing := filepath.Join(dir, "node_modules", "ui", "missing.d.ts")
	require.Equal(t, []string{fmt.Sprintf(
		"cannot resolve import %q: reading %s, referenced from %s: open %s: no such file or directory",
		"ui", missing, entry, missing)}, errorMessagesOf(res.Errors))
}

// TestNodeModulesImportBindsDTSImports covers a package whose `.d.ts` imports names
