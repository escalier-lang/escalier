// TestNodeModulesImportReportsAMissingPackage asserts that a bare import with no types
// anywhere names each place the lookup tried.
func TestNodeModulesImportReportsAMissingPackage(t *testing.T) {
	t.Parallel()

	res, dir := inferAgainstNodeModules(t, `import "absent" as a`, nil)
	var tried []string
	for current := dir; ; current = filepath.Dir(current) {
		tried = append(tried,
			filepath.Join(current, "node_modules", "absent"),
			filepath.Join(current, "node_modules", "@types", "absent"))
		if filepath.Dir(current) == current {
			break
		}
	}
	require.Equal(t, []string{fmt.Sprintf("cannot resolve import %q: no types found for %q; looked in %s",
		"absent", "absent", strings.Join(tried, ", "))}, errorMessagesOf(res.Errors))
}

// TestNodeModulesImportReportsAnUnloadablePackage covers a package whose entry point
// resolves but does not load. Each case wants the one error the import reports.
func TestNodeModulesImportReportsAnUnloadablePackage(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		contents string
		want     func(dir string) string
	}{
		{
			name:     "an entry point that does not parse",
			contents: `export declare const ;`,
			want: func(dir string) string {
				return fmt.Sprintf("cannot resolve import %q: parse errors in %s: 21-22: Expected identifier; 0-6: Unexpected token",
					"broken", filepath.Join(dir, "node_modules", "broken", "index.d.ts"))
			},
		},
		{
			name:     "an entry point that declares nothing for the package",
			contents: `declare module "other" { export const v: number; }`,
			want: func(dir string) string {
				return fmt.Sprintf("cannot resolve import %q: %s declares no exports and no `declare module %q` block",
					"broken", filepath.Join(dir, "node_modules", "broken", "index.d.ts"), "broken")
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			res, dir := inferAgainstNodeModules(t, `import "broken" as b`, map[string]string{
				"node_modules/broken/index.d.ts": test.contents,
			})
			require.Equal(t, []string{test.want(dir)}, errorMessagesOf(res.Errors))
		})
	}
}

// TestNodeModulesImportFollowsASymlink asserts that a package whose `node_modules` entry
// is a symlink resolves through it, the layout pnpm installs.
func TestNodeModulesImportFollowsASymlink(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, withPreludeClasses(map[string]string{
		".pnpm/linked@1.0.0/node_modules/linked/index.d.ts": `export declare const version: string;`,
	}))
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "node_modules"), 0o755))
	require.NoError(t, os.Symlink(filepath.Join(dir, ".pnpm", "linked@1.0.0", "node_modules", "linked"),
		filepath.Join(dir, "node_modules", "linked")))
	res := InferModuleAgainstStdlib(parseModule(t, "import \"linked\" as l\nval v = l.version"), dir,
		Options{PackageDir: dir})
	require.Empty(t, errorMessagesOf(res.Errors))
	require.Equal(t, "string", soltype.Print(inferredValueType(t, res.Scope, "v")))
}

// TestPseudoPackageImportReportsAtItsImportBesideAnNpmImport asserts that a pseudo-package
// imported after an npm package still reports its diagnostics at its own import. The npm
// import binds the ambient scope, and that load would otherwise reach the pseudo-package
