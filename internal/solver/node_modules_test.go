// TestNodeModulesImportReportsADTSImportError covers a `.d.ts` import that binds
// nothing. Each case wants the one error the importing package reports, which reaches
// the entry module wrapped in the package's own diagnostic.
func TestNodeModulesImportReportsADTSImportError(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		files    map[string]string
		contents string
		want     func(dir string) string
	}{
		{
			name:     "a named import the package does not export",
			files:    map[string]string{"node_modules/dep/index.d.ts": `export interface Props { color: string }`},
			contents: "import { Missing } from \"dep\";\nexport declare const v: string;",
			want: func(string) string {
				return `"dep" has no export named "Missing"`
			},
		},
		{
			name:     "a sibling file that does not exist",
			contents: "import * as M from \"./missing\";\nexport declare const v: string;",
			want: func(dir string) string {
				missing := filepath.Join(dir, "node_modules", "ui", "missing.d.ts")
				return fmt.Sprintf("cannot resolve import %q: reading %s: open %s: no such file or directory",
					missing, missing, missing)
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"node_modules/ui/index.d.ts": test.contents}
			for path, contents := range test.files {
				files[path] = contents
			}
			res, dir := inferAgainstNodeModules(t, `import "ui" as ui`, files)
			require.Equal(t, []string{fmt.Sprintf("package %q (%s) has 1 error(s):\n  %s",
				"ui", filepath.Join(dir, "node_modules", "ui", "index.d.ts"), test.want(dir))},
				errorMessagesOf(res.Errors))
		})
	}
}

// TestNodeModulesImportLeavesDTSImportsUnchecked asserts that an import a package's
// `.d.ts` writes is not checked against the project's dependencies, which list only
// what the project imports itself.
func TestNodeModulesImportLeavesDTSImportsUnchecked(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, withPreludeClasses(map[string]string{
		"node_modules/dep/index.d.ts": `export interface Props { color: string }`,
		"node_modules/ui/index.d.ts":  "import * as D from \"dep\";\nexport declare const p: D.Props;",
	}))
	res := InferModuleAgainstStdlib(parseModule(t, "import \"ui\" as ui\nval c = ui.p.color"), dir,
		Options{PackageDir: dir, Dependencies: set.FromSlice([]string{"ui"})})
	require.Empty(t, errorMessagesOf(res.Errors))
	require.Equal(t, "string", soltype.Print(inferredValueType(t, res.Scope, "c")))
}

// TestDTSImportURI covers the URI an import inside a `.d.ts` loads through. The tree
// is the package directory, and each case names the importing file and the file the
// URI should reach, both relative to the tree.
func TestDTSImportURI(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, map[string]string{
		"node_modules/dep/index.d.ts":                 `export {};`,
		"node_modules/ui/index.d.ts":                  `export {};`,
		"node_modules/ui/extra.d.ts":                  `export {};`,
		"node_modules/ui/esm.d.mts":                   `export {};`,
		"node_modules/ui/sub/index.d.ts":              `export {};`,
		"node_modules/ui/node_modules/own/index.d.ts": `export {};`,
		"node_modules/@types/scope__pkg/index.d.ts":   `export {};`,
		"node_modules/@types/scope__pkg/more.d.ts":    `export {};`,
		"vendor/lib.d.ts":                             `export {};`,
		"vendor/types.d.ts":                           `export {};`,
	})
	abs := func(rel string) string { return filepath.Join(dir, filepath.FromSlash(rel)) }

	tests := []struct {
		name string
		spec string
		from string
		want string
	}{
		{name: "a package the project reaches", spec: "dep", from: "node_modules/ui/index.d.ts", want: "dep"},
		{
			name: "a package only the importing file reaches",
			spec: "own", from: "node_modules/ui/index.d.ts",
			want: abs("node_modules/ui/node_modules/own/index.d.ts"),
		},
		{name: "a package nothing reaches", spec: "absent", from: "node_modules/ui/index.d.ts", want: "absent"},
		{name: "a sibling file", spec: "./extra", from: "node_modules/ui/index.d.ts", want: "ui/extra"},
		{name: "a sibling file with a .js extension", spec: "./extra.js", from: "node_modules/ui/index.d.ts", want: "ui/extra"},
		{name: "a sibling file with a .mjs extension", spec: "./esm.mjs", from: "node_modules/ui/index.d.ts", want: abs("node_modules/ui/esm.d.mts")},
		{name: "the package's own entry point", spec: "./", from: "node_modules/ui/extra.d.ts", want: "ui"},
		{name: "a directory's index", spec: "./sub", from: "node_modules/ui/index.d.ts", want: "ui/sub"},
		{name: "a parent directory's index", spec: "..", from: "node_modules/ui/sub/index.d.ts", want: "ui"},
		{name: "a file of a scoped @types package", spec: "./more", from: "node_modules/@types/scope__pkg/index.d.ts", want: "@scope/pkg/more"},
		{name: "a file under no node_modules", spec: "./types", from: "vendor/lib.d.ts", want: abs("vendor/types.d.ts")},
		{name: "a sibling file that does not exist", spec: "./missing", from: "node_modules/ui/index.d.ts", want: abs("node_modules/ui/missing.d.ts")},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			require.Equal(t, test.want, dtsImportURI(test.spec, abs(test.from), dir))
		})
	}
}

// TestNodeModulesImportRejectsAnAbsolutePath asserts that the entry module cannot load a
// `.d.ts` by its absolute path, the URI form only a package's own imports are given.
func TestNodeModulesImportRejectsAnAbsolutePath(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, withPreludeClasses(map[string]string{
		"node_modules/plain/index.d.ts": `export declare const version: string;`,
	}))
	path := filepath.Join(dir, "node_modules", "plain", "index.d.ts")
	res := InferModuleAgainstStdlib(parseModule(t, fmt.Sprintf("import %q as p", path)), dir, Options{PackageDir: dir})
	require.Equal(t, []string{fmt.Sprintf("cannot resolve import %q: %q is a path, not a package name", path, path)},
		errorMessagesOf(res.Errors))
}
