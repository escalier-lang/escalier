// TestScriptReadsANpmReadonlyCollection covers a script checked against a library that
// imports an npm package. A script binds no imports of its own, so it reaches the package
// through the library's exports. A readonly collection the package returns stays a `'static`
// borrow in the script, and a readonly const stays a module-level value of the package.
func TestScriptReadsANpmReadonlyCollection(t *testing.T) {
	t.Parallel()

	dir := seedStdlib(t, map[string]string{"node_modules/dep/index.d.ts": `export declare function make(): readonly number[];
export declare const value: readonly number[];`})
	ctx := context.Background()
	libSource := &ast.Source{ID: 0, Path: "lib/index.esc", Contents: `import "dep" as d
export val make = d.make
export val value = d.value`}
	module, libParseErrors := parser.ParseLibFiles(ctx, []*ast.Source{libSource})
	require.Empty(t, libParseErrors)
	lib := InferModuleAgainstStdlib(module, benchTree, Options{PackageDir: dir})
	require.Empty(t, lib.Errors)

	tests := []struct {
		name string
		src  string
		want []string
	}{
		{
			name: "a call result bound as mutable at the top level",
			src:  `val m: mut Array<number> = make()`,
			want: []string{"1:12-1:17: cannot constrain immutable Array<number> <: mutable Array<number>"},
		},
		{
			name: "a call result bound as mutable in a function",
			src: `fn f() {
	val m: mut Array<number> = make()
}`,
			want: []string{"2:13-2:18: cannot constrain immutable Array<number> <: mutable Array<number>"},
		},
		{
			name: "a call result passed to an owned parameter",
			src: `fn take(x: Array<number>) {}
take(make())`,
			want: []string{"2:6-2:12: cannot use borrowed &Array<number> as owned Array<number>"},
		},
		{
			name: "a const moved in a function",
			src: `fn f() {
	val a = value
}`,
			want: []string{"2:10-2:15: cannot move module-level value 'value' inside a function. Borrow it with `&value`"},
		},
		{
			name: "an element read off a call result",
			src: `val a = make()
val n = a[0]`,
			want: nil,
		},
		{
			name: "a const borrowed in a function",
			src: `fn f() {
	val a = &value
}`,
			want: nil,
		},
	}
	for i, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			scriptSource := &ast.Source{ID: 1 + i, Path: "bin/index.esc", Contents: tt.src}
			script, scriptParseErrors := parser.NewParser(ctx, scriptSource).ParseScript()
			require.Empty(t, scriptParseErrors)
			registerTestSources(t, map[int]*ast.Source{libSource.ID: libSource, scriptSource.ID: scriptSource})
			_, _, errs := InferScriptInLib(script, lib)
			require.Equal(t, tt.want, messagesWithSpan(t, errs))
		})
	}
}

// TestNodeModulesImportReadonlyCollectionTypes covers the types an npm package's readonly
// collections take once imported. A readonly collection a function returns is a `'static`
// borrow, at any depth of the return type. One a function takes as a parameter, or a const
// holds, stays owned, and so does one a callback parameter returns. Every readonly return
// reads as shared until #2219 tells a fresh collection from a shared one.
func TestNodeModulesImportReadonlyCollectionTypes(t *testing.T) {
	t.Parallel()

	dts := `export declare function make(): readonly number[];
export declare function maybe(): ReadonlyMap<string, number> | undefined;
export declare function box(): { items: ReadonlySet<number> };
export declare function later(): Promise<readonly number[]>;
export declare function sum(xs: readonly number[]): number;
export declare const value: readonly number[];
export declare const mk: () => readonly string[];
export declare function onItems(): (cb: () => readonly number[]) => void;
export declare function withOpts(opts: { items(): readonly number[] }): number;
export declare class C {
	list(): readonly string[];
	static of(): ReadonlyArray<number>;
}`
	src := `import "dep" as d
val make = d.make
val made = d.make()
val maybe = d.maybe
val box = d.box
val later = d.later
val sum = d.sum
val value = d.value
val mk = d.mk
val onItems = d.onItems
val withOpts = d.withOpts
val mut c = d.C()
val list = c.list
val of = d.C.of`
	dir := seedStdlib(t, map[string]string{"node_modules/dep/index.d.ts": dts})
	res := InferModuleAgainstStdlib(parseModule(t, src), benchTree, Options{PackageDir: dir})
	require.Empty(t, messagesWithSpan(t, res.Errors))

	tests := []struct {
		name string
		want string
	}{
		{name: "make", want: "fn () -> &'static Array<number>"},
		{name: "made", want: "&'static Array<number>"},
		{name: "maybe", want: "fn () -> &'static Map<string, number> | undefined"},
		{name: "box", want: "fn () -> {items: &'static Set<number>}"},
		{name: "later", want: "fn () -> Promise<&'static Array<number>>"},
		{name: "sum", want: "fn (xs: Array<number>) -> number"},
		{name: "value", want: "Array<number>"},
		{name: "mk", want: "fn () -> &'static Array<string>"},
		{name: "onItems", want: "fn () -> fn (cb: fn () -> Array<number>) -> unknown"},
		{name: "withOpts", want: "fn (opts: {items() -> Array<number>}) -> number"},
		{name: "list", want: "fn () -> &'static Array<string>"},
		{name: "of", want: "fn () -> &'static Array<number>"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			require.Equal(t, tt.want, soltype.Print(inferredValueType(t, res.Scope, tt.name)))
		})
	}
}
