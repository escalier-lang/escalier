package solver

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/escalier-lang/escalier/internal/ast"
	"github.com/escalier-lang/escalier/internal/dts_parser"
	"github.com/escalier-lang/escalier/internal/dts_to_esc"
	"github.com/escalier-lang/escalier/internal/resolver"
)

// NodeModulesSource returns a ModuleSource that reads an npm package's types from
// the `node_modules` directories at and above dir.
//
// A URI resolves to the first of these that holds types:
//
//  1. `node_modules/<uri>`, a package that ships its own types;
//  2. `node_modules/@types/<uri>`, a package whose types are published apart.
//
// Each directory from dir up to the filesystem root is tried in turn, the way
// Node looks a package up. A subpath URI such as `lodash/fp` resolves to the
// directory of that name inside the package, or to a `.d.ts` file of that name.
//
// The package is the entry point's module declarations. A file with top-level
// exports declares them directly, and a file without them declares the package
// in a `declare module "<uri>" { … }` block.
func NodeModulesSource(dir string) ModuleSource {
	return func(uri string) (*ast.Module, string, error) {
		path, err := resolveTypesEntryPoint(dir, uri)
		if err != nil {
			return nil, "", err
		}
		contents, err := os.ReadFile(path)
		if err != nil {
			return nil, "", fmt.Errorf("reading %s: %w", path, err)
		}
		module, err := stdlibParses.get(path, string(contents), func(sourceID int) (*ast.Module, error) {
			return parseTypesModule(uri, path, string(contents), sourceID)
		})
		if err != nil {
			return nil, "", err
		}
		return module, path, nil
	}
}

// resolveTypesEntryPoint returns the `.d.ts` file the types for uri start at, looking
// in the `node_modules` directories at and above dir. The error names every place it
// looked when none holds types.
func resolveTypesEntryPoint(dir, uri string) (string, error) {
	var tried []string
	for current := dir; ; {
		nodeModules := filepath.Join(current, "node_modules")
		for _, pkgDir := range []string{
			filepath.Join(nodeModules, filepath.FromSlash(uri)),
			filepath.Join(nodeModules, "@types", filepath.FromSlash(typesPackageName(uri))),
		} {
			tried = append(tried, pkgDir)
			if isDir(pkgDir) {
				if path, err := resolver.GetTypesEntryPoint(pkgDir); err == nil {
					return path, nil
				}
			}
			// A subpath can name a file rather than a directory, as
			// `react/jsx-runtime` names `react/jsx-runtime.d.ts`.
			if file := pkgDir + ".d.ts"; isFile(file) {
				return file, nil
			}
		}
		parent := filepath.Dir(current)
		if parent == current {
			break
		}
		current = parent
	}
	return "", fmt.Errorf("no types found for %q; looked in %s", uri, strings.Join(tried, ", "))
}

// typesPackageName returns the `@types` package name for uri. A scoped package
// `@scope/name` publishes its types as `@types/scope__name`, and any subpath
// after the package name is kept.
func typesPackageName(uri string) string {
	if !strings.HasPrefix(uri, "@") {
		return uri
	}
	scope, rest, found := strings.Cut(uri[1:], "/")
	if !found {
		return uri
	}
	return scope + "__" + rest
}

// isDir reports whether path names a directory, following a symlink.
func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

// isFile reports whether path names a regular file, following a symlink.
func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// parseTypesModule parses the `.d.ts` at path and converts the declarations that
// make up the package uri names. sourceID is the id the parse records on every span.
func parseTypesModule(uri, path, contents string, sourceID int) (*ast.Module, error) {
	source := &ast.Source{ID: sourceID, Path: path, Contents: contents}
	dtsModule, parseErrs := dts_parser.NewDtsParser(source).ParseModule()
	if len(parseErrs) > 0 {
		messages := make([]string, 0, len(parseErrs))
		for _, pe := range parseErrs {
			messages = append(messages, pe.String())
		}
		return nil, fmt.Errorf("parse errors in %s: %s", path, strings.Join(messages, "; "))
	}

	decls, err := packageDecls(uri, path, dts_parser.ClassifyDTSFile(dtsModule))
	if err != nil {
		return nil, err
	}
	module, err := dts_to_esc.ConvertModuleWithOverrides(&dts_parser.Module{Statements: decls}, nil, uri)
	if err != nil {
		return nil, fmt.Errorf("converting %s: %w", path, err)
	}
	module.Sources[sourceID] = source
	return module, nil
}

// packageDecls returns the statements that declare the package uri names in the
// file classified as classification.
func packageDecls(uri, path string, classification *dts_parser.FileClassification) ([]dts_parser.Statement, error) {
	if classification.HasTopLevelExports {
		return classification.PackageDecls, nil
	}
	for _, named := range classification.NamedModules {
		if named.ModuleName == uri {
			return named.Decls, nil
		}
	}
	return nil, fmt.Errorf("%s declares no exports and no `declare module %q` block", path, uri)
}
