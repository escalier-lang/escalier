// NodeModulesSource returns a ModuleSource that reads an npm package's types from
// the `node_modules` directories at and above dir, found the way
// resolver.ResolveTypesEntryPoint finds them.
//
// The package's declarations come from its entry point and every file a reference
// directive in it reaches. collectTypesFiles lists those files, and packageDecls
// says which declarations of each make up the package.
//
// A uri that is an absolute path names the entry point itself. dtsImportURI
// gives such a uri to an import inside a `.d.ts` when no package specifier
// reaches the imported file from dir.
func NodeModulesSource(dir string) ModuleSource {
	return func(uri string) (*ast.Module, string, error) {
		entry := uri
		if !filepath.IsAbs(uri) {
			resolved, err := resolver.ResolveTypesEntryPoint(uri, dir)
			if err != nil {
				return nil, "", err
			}
			entry = resolved
		}
		files, err := collectTypesFiles(entry)
		if err != nil {
			return nil, "", err
		}
		paths := make([]string, len(files))
		bodies := make([]string, len(files))
		for i, file := range files {
			paths[i] = file.path
			bodies[i] = file.contents
		}
		// The cache is keyed on uri as well as the files, since uri picks the
		// `declare module "<uri>"` block the package is read from. Two URIs can reach
		// the same files: `import "pkg"` and `import "pkg/index"` both resolve to
		// `node_modules/pkg/index.d.ts`. It is keyed on dir too, since the URIs the
		// files' own imports are given depend on it.
		module, err := stdlibParses.getNamedGroup(uri+"\x00"+dir, paths, bodies, func(firstSourceID int) (*ast.Module, error) {
			return parseTypesModule(uri, dir, files, firstSourceID)
		})
		if err != nil {
			return nil, "", err
		}
		return module, entry, nil
	}
}

// listedDependency reports whether deps lists the package uri names, either under its
// own name or as its `@types` package. A subpath is checked by its package name, so
// `react/jsx-runtime` is listed when `react` or `@types/react` is.
func listedDependency(deps set.Set[string], uri string) bool {
	name := resolver.PackageName(uri)
	return deps.Contains(name) || deps.Contains("@types/"+resolver.TypesPackageName(name))
}

// UnlistedDependencyError reports an import of an npm package the project's
// package.json does not list.
type UnlistedDependencyError struct {
	// Package is the package the import names, without any subpath.
	Package string
	span    ast.Span
}

func (e *UnlistedDependencyError) Message() string {
	return fmt.Sprintf("%q is not listed in package.json dependencies", e.Package)
}
func (e *UnlistedDependencyError) Span() ast.Span      { return e.span }
func (e *UnlistedDependencyError) Related() []ast.Span { return nil }
func (e *UnlistedDependencyError) isSolverError()      {}

// typesFile is one `.d.ts` file a package's declarations are read from.
type typesFile struct {
	path     string
	contents string
}

// collectTypesFiles returns the entry point and every file its reference directives
// reach, the entry point first and each file once. A directive is followed this way:
//
//   - `path` names a file relative to the file holding the directive, with `.d.ts`
//     added when the file named does not exist;
//   - `types` names a types package, resolved from that file's directory by
//     resolver.ResolveTypeReference;
//   - `lib` is not followed.
//
// A `path` whose file does not exist is an error naming both files. A `types` that
// does not resolve is not followed.
func collectTypesFiles(entry string) ([]typesFile, error) {
	var files []typesFile
	seen := set.NewSet[string]()
	var visit func(path, from string) error
	visit = func(path, from string) error {
		if seen.Contains(path) {
			return nil
		}
		seen.Add(path)
		contents, err := os.ReadFile(path)
		if err != nil {
			if from != "" {
				return fmt.Errorf("reading %s, referenced from %s: %w", path, from, err)
			}
			return fmt.Errorf("reading %s: %w", path, err)
		}
		files = append(files, typesFile{path: path, contents: string(contents)})
		dir := filepath.Dir(path)
		for _, directive := range dts_parser.ParseReferenceDirectives(string(contents)) {
			var target string
			switch directive.Kind {
			case dts_parser.ReferencePath:
				target = filepath.Join(dir, filepath.FromSlash(directive.Value))
				if !fileExists(target) && fileExists(target+".d.ts") {
					target += ".d.ts"
				}
			case dts_parser.ReferenceTypes:
				resolved, err := resolver.ResolveTypeReference(directive.Value, dir)
				// A package often references `node` for a few declarations an importer
				// may never reach, so a project without `@types/node` still loads it.
				if err != nil {
					continue
				}
				target = resolved
			default:
				// A `lib` names part of TypeScript's standard library, which the
				// ambient scope already holds.
				continue
			}
			if err := visit(target, path); err != nil {
				return err
			}
		}
		return nil
	}
	if err := visit(entry, ""); err != nil {
		return nil, err
	}
	return files, nil
}

// fileExists reports whether path names a file or directory.
func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// parseTypesModule parses files and converts the declarations that make up the
// package `uri` names. The file at index i parses under source id firstSourceID+i.
//
// The module holds one ast.File per file, carrying the imports that file writes.
// Each import's URI is the one dtsImportURI gives for it against dir, the
// directory the run resolves packages from.
func parseTypesModule(uri, dir string, files []typesFile, firstSourceID int) (*ast.Module, error) {
	sources := make(map[int]*ast.Source, len(files))
	classifications := make([]*dts_parser.FileClassification, len(files))
	for i, file := range files {
		source := &ast.Source{ID: firstSourceID + i, Path: file.path, Contents: file.contents}
		dtsModule, parseErrs := dts_parser.NewDtsParser(source).ParseModule()
		if len(parseErrs) > 0 {
			messages := make([]string, 0, len(parseErrs))
			for _, pe := range parseErrs {
				messages = append(messages, pe.String())
			}
			return nil, fmt.Errorf("parse errors in %s: %s", file.path, strings.Join(messages, "; "))
		}
		sources[source.ID] = source
		classifications[i] = dts_parser.ClassifyDTSFile(dtsModule)
	}

	decls, err := packageDecls(uri, files[0].path, classifications)
	if err != nil {
		return nil, err
	}
	module, err := dts_to_esc.ConvertModuleWithOverrides(&dts_parser.Module{Statements: decls}, nil, uri)
	if err != nil {
		return nil, fmt.Errorf("converting %s: %w", files[0].path, err)
	}
	for id, source := range sources {
		module.Sources[id] = source
	}
	for i, file := range files {
		module.Files = append(module.Files, &ast.File{
			Path:     file.path,
			SourceID: firstSourceID + i,
			Imports:  dtsImportStmts(classifications[i].Imports, file.path, dir),
		})
	}
	return module, nil
}

// dtsImportStmts converts the imports a `.d.ts` at path writes into the import
// statements that bind the same names:
//
//   - `import * as X from "pkg"` binds the package as the namespace X;
//   - `import { a, b as c } from "pkg"` binds the members a and b, as a and c;
//   - `import X from "pkg"` binds the member `default` as X.
//
// `import type` binds what the same import without `type` binds. A side-effect
// `import "pkg"` binds nothing and is left out. So is an import whose specifier
// has a scheme, such as `node:fs`, since a scheme names an Escalier
// pseudo-package rather than the npm module the `.d.ts` means. Each statement's
// URI is dtsImportURI's for the specifier, path and dir.
func dtsImportStmts(imports []*dts_parser.ImportDecl, path, dir string) []*ast.ImportStmt {
	var stmts []*ast.ImportStmt
	for _, decl := range imports {
		hasNames := decl.DefaultImport != nil || decl.NamedImports != nil
		if IsSchemePrefixedImport(decl.From) || (decl.NamespaceAs == nil && !hasNames) {
			continue
		}
		uri := dtsImportURI(decl.From, path, dir)
		if decl.NamespaceAs != nil {
			stmts = append(stmts, ast.NewImportStmt(uri, decl.NamespaceAs.Name, nil, decl.Span()))
		}
		if !hasNames {
			continue
		}
		// Non-nil even when empty, so `import {} from "pkg"` binds no namespace.
		names := []*ast.ImportName{}
		if decl.DefaultImport != nil {
			names = append(names, &ast.ImportName{Imported: defaultExport, Local: decl.DefaultImport.Name})
		}
		for _, spec := range decl.NamedImports {
			names = append(names, &ast.ImportName{Imported: spec.Imported.Name, Local: spec.Local.Name})
		}
		stmt := ast.NewImportStmt(uri, "", nil, decl.Span())
		stmt.Names = names
		stmts = append(stmts, stmt)
	}
	return stmts
}

// dtsImportURI returns the URI an import of spec, written in the `.d.ts` at
// path, loads through NodeModulesSource(dir).
//
// The target file is found from path's directory. A relative spec names a file
// beside path, found the way relativeTypesFile finds it. Any other spec names a
// package, found by resolver.ResolveTypesEntryPoint. The URI is then:
//
//   - a package specifier that reaches the target from dir, when one does, so the
//     target loads once however it is imported;
//   - the target's absolute path otherwise.
//
// A package spec that does not resolve from path's directory is returned as
// written, so the load reports why.
func dtsImportURI(spec, path, dir string) string {
	fromDir := filepath.Dir(path)
	if !isRelativeSpecifier(spec) {
		target, err := resolver.ResolveTypesEntryPoint(spec, fromDir)
		if err != nil {
			return spec
		}
		if resolvesTo(spec, dir, target) {
			return spec
		}
		return target
	}
	target := relativeTypesFile(filepath.Join(fromDir, filepath.FromSlash(spec)))
	for _, name := range packageSpecifiers(target) {
		if resolvesTo(name, dir, target) {
			return name
		}
	}
	return target
}

// isRelativeSpecifier reports whether spec is a path relative to the importing
// file, rather than a package name.
func isRelativeSpecifier(spec string) bool {
	return spec == "." || spec == ".." || strings.HasPrefix(spec, "./") || strings.HasPrefix(spec, "../")
}

// relativeTypesFile returns the declaration file a relative import resolving to
// path names. It tries in turn:
//
//  1. path itself, when it ends in `.d.ts`, `.d.mts` or `.d.cts`;
//  2. path with a `.js`, `.mjs` or `.cjs` extension replaced by `.d.ts`, `.d.mts`
//     or `.d.cts`, or with `.d.ts` added when it has none of them;
//  3. `index.d.ts` inside path.
//
// When none exists it returns the second candidate, so the load reports the
// file it could not read.
func relativeTypesFile(path string) string {
	for _, ext := range []string{".d.ts", ".d.mts", ".d.cts"} {
		if strings.HasSuffix(path, ext) && fileExists(path) {
			return path
		}
	}
	declFile := path + ".d.ts"
	for _, ext := range []struct{ js, decl string }{{".js", ".d.ts"}, {".mjs", ".d.mts"}, {".cjs", ".d.cts"}} {
		if base, found := strings.CutSuffix(path, ext.js); found {
			declFile = base + ext.decl
			break
		}
	}
	if fileExists(declFile) {
		return declFile
	}
	if index := filepath.Join(path, "index.d.ts"); fileExists(index) {
		return index
	}
	return declFile
}

// packageSpecifiers returns the package specifiers that could name target, a file
// under a `node_modules` directory, most specific last. A file at
// `node_modules/@types/react/jsx-runtime.d.ts` gives `react` and
// `react/jsx-runtime`. A file that is under no `node_modules` gives none.
func packageSpecifiers(target string) []string {
	segments := strings.Split(filepath.ToSlash(target), "/")
	last := -1
	for i, segment := range segments {
		if segment == "node_modules" {
			last = i
		}
	}
	if last < 0 {
		return nil
	}
	rest := segments[last+1:]
	var name string
	switch {
	case len(rest) >= 3 && rest[0] == "@types":
		// `@types/scope__pkg` publishes the types of `@scope/pkg`.
		name = rest[1]
		if scope, pkg, scoped := strings.Cut(name, "__"); scoped {
			name = "@" + scope + "/" + pkg
		}
		rest = rest[2:]
	case len(rest) >= 3 && strings.HasPrefix(rest[0], "@"):
		name = rest[0] + "/" + rest[1]
		rest = rest[2:]
	case len(rest) >= 2:
		name = rest[0]
		rest = rest[1:]
	default:
		return nil
	}
	sub := strings.TrimSuffix(strings.Join(rest, "/"), ".d.ts")
	sub = strings.TrimSuffix(sub, "/index")
	if sub == "index" {
		return []string{name}
	}
	return []string{name, name + "/" + sub}
}

// resolvesTo reports whether spec, resolved from dir, reaches the same file as
// target.
func resolvesTo(spec, dir, target string) bool {
	resolved, err := resolver.ResolveTypesEntryPoint(spec, dir)
	if err != nil {
		return false
	}
	a, errA := os.Stat(resolved)
	b, errB := os.Stat(target)
	return errA == nil && errB == nil && os.SameFile(a, b)
}

// packageDecls returns the statements that make up the package `uri` names, read from
// classifications. The first classification is the entry point's, and the rest are the
// files its reference directives reach. The package is made of:
//
//   - its own declarations, which are the entry point's when it has top-level exports,
//     or else those of every `declare module "<uri>" { … }` block the files hold;
//   - the global declarations of every file, which its own declarations can name.
//
// entry names the entry point in the error for a package with no declarations of its
// own.
func packageDecls(uri, entry string, classifications []*dts_parser.FileClassification) ([]dts_parser.Statement, error) {
	decls, found := ownDecls(uri, classifications)
	if !found {
		return nil, fmt.Errorf("%s declares no exports and no `declare module %q` block", entry, uri)
	}
	for _, classification := range classifications {
		decls = append(decls, classification.GlobalDecls...)
	}
	return decls, nil
}

// ownDecls returns the declarations packageDecls calls the package's own, and reports
// whether the files hold any. The slice is a fresh copy the caller may append to.
func ownDecls(uri string, classifications []*dts_parser.FileClassification) ([]dts_parser.Statement, bool) {
	if classifications[0].HasTopLevelExports {
		return append([]dts_parser.Statement(nil), classifications[0].PackageDecls...), true
	}
	var decls []dts_parser.Statement
	found := false
	for _, classification := range classifications {
		for _, named := range classification.NamedModules {
			if named.ModuleName == uri {
				decls = append(decls, named.Decls...)
				found = true
			}
		}
	}
	return decls, found
}
