// NodeModulesSource returns a ModuleSource that reads an npm package's types from
// the `node_modules` directories at and above dir, found the way
// resolver.ResolveTypesEntryPoint finds them.
//
// The package's declarations come from its entry point and every file a reference
// directive in it reaches. collectTypesFiles lists those files, and packageDecls
// says which declarations of each make up the package.
func NodeModulesSource(dir string) ModuleSource {
	return func(uri string) (*ast.Module, string, error) {
		entry, err := resolver.ResolveTypesEntryPoint(uri, dir)
		if err != nil {
			return nil, "", err
		}
		files, err := collectTypesFiles(entry)
		if err != nil {
			return nil, "", err
		}
		paths := make([]string, len(files))
		bodies := make([]string, len(files))
		for i, file := range files {
			paths[i] = file.path
			bodies[i] = file.contents
		}
		// The cache is keyed on uri as well as the files, since uri picks the
		// `declare module "<uri>"` block the package is read from. Two URIs can reach
		// the same files: `import "pkg"` and `import "pkg/index"` both resolve to
		// `node_modules/pkg/index.d.ts`.
		module, err := stdlibParses.getNamedGroup(uri, paths, bodies, func(firstSourceID int) (*ast.Module, error) {
			return parseTypesModule(uri, files, firstSourceID)
		})
		if err != nil {
			return nil, "", err
		}
		return module, entry, nil
	}
}

// listedDependency reports whether deps lists the package uri names, either under its
// own name or as its `@types` package. A subpath is checked by its package name, so
// `react/jsx-runtime` is listed when `react` or `@types/react` is.
func listedDependency(deps set.Set[string], uri string) bool {
	name := resolver.PackageName(uri)
	return deps.Contains(name) || deps.Contains("@types/"+resolver.TypesPackageName(name))
}

// UnlistedDependencyError reports an import of an npm package the project's
// package.json does not list.
type UnlistedDependencyError struct {
	// Package is the package the import names, without any subpath.
	Package string
	span    ast.Span
}

func (e *UnlistedDependencyError) Message() string {
	return fmt.Sprintf("%q is not listed in package.json dependencies", e.Package)
}
func (e *UnlistedDependencyError) Span() ast.Span      { return e.span }
func (e *UnlistedDependencyError) Related() []ast.Span { return nil }
func (e *UnlistedDependencyError) isSolverError()      {}

// typesFile is one `.d.ts` file a package's declarations are read from.
type typesFile struct {
	path     string
	contents string
}

// collectTypesFiles returns the entry point and every file its reference directives
// reach, the entry point first and each file once. A directive is followed this way:
//
//   - `path` names a file relative to the file holding the directive, with `.d.ts`
//     added when the file named does not exist;
//   - `types` names a types package, resolved from that file's directory by
//     resolver.ResolveTypeReference;
//   - `lib` is not followed.
//
// A `path` whose file does not exist is an error naming both files. A `types` that
// does not resolve is not followed.
func collectTypesFiles(entry string) ([]typesFile, error) {
	var files []typesFile
	seen := set.NewSet[string]()
	var visit func(path, from string) error
	visit = func(path, from string) error {
		if seen.Contains(path) {
			return nil
		}
		seen.Add(path)
		contents, err := os.ReadFile(path)
		if err != nil {
			if from != "" {
				return fmt.Errorf("reading %s, referenced from %s: %w", path, from, err)
			}
			return fmt.Errorf("reading %s: %w", path, err)
		}
		files = append(files, typesFile{path: path, contents: string(contents)})
		dir := filepath.Dir(path)
		for _, directive := range dts_parser.ParseReferenceDirectives(string(contents)) {
			var target string
			switch directive.Kind {
			case dts_parser.ReferencePath:
				target = filepath.Join(dir, filepath.FromSlash(directive.Value))
				if !fileExists(target) && fileExists(target+".d.ts") {
					target += ".d.ts"
				}
			case dts_parser.ReferenceTypes:
				resolved, err := resolver.ResolveTypeReference(directive.Value, dir)
				// A package often references `node` for a few declarations an importer
				// may never reach, so a project without `@types/node` still loads it.
				if err != nil {
					continue
				}
				target = resolved
			default:
				// A `lib` names part of TypeScript's standard library, which the
				// ambient scope already holds.
				continue
			}
			if err := visit(target, path); err != nil {
				return err
			}
		}
		return nil
	}
	if err := visit(entry, ""); err != nil {
		return nil, err
	}
	return files, nil
}

// fileExists reports whether path names a file or directory.
func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// parseTypesModule parses files and converts the declarations that make up the
// package `uri` names. The file at index i parses under source id firstSourceID+i.
func parseTypesModule(uri string, files []typesFile, firstSourceID int) (*ast.Module, error) {
	sources := make(map[int]*ast.Source, len(files))
	classifications := make([]*dts_parser.FileClassification, len(files))
	for i, file := range files {
		source := &ast.Source{ID: firstSourceID + i, Path: file.path, Contents: file.contents}
		dtsModule, parseErrs := dts_parser.NewDtsParser(source).ParseModule()
		if len(parseErrs) > 0 {
			messages := make([]string, 0, len(parseErrs))
			for _, pe := range parseErrs {
				messages = append(messages, pe.String())
			}
			return nil, fmt.Errorf("parse errors in %s: %s", file.path, strings.Join(messages, "; "))
		}
		sources[source.ID] = source
		classifications[i] = dts_parser.ClassifyDTSFile(dtsModule)
	}

	decls, err := packageDecls(uri, files[0].path, classifications)
	if err != nil {
		return nil, err
	}
	module, err := dts_to_esc.ConvertModuleWithOverrides(&dts_parser.Module{Statements: decls}, nil, uri)
	if err != nil {
		return nil, fmt.Errorf("converting %s: %w", files[0].path, err)
	}
	for id, source := range sources {
		module.Sources[id] = source
	}
	return module, nil
}

// packageDecls returns the statements that make up the package `uri` names, read from
// classifications. The first classification is the entry point's, and the rest are the
// files its reference directives reach. The package is made of:
//
//   - its own declarations, which are the entry point's when it has top-level exports,
//     or else those of every `declare module "<uri>" { … }` block the files hold;
//   - the global declarations of every file, which its own declarations can name.
//
// entry names the entry point in the error for a package with no declarations of its
// own.
func packageDecls(uri, entry string, classifications []*dts_parser.FileClassification) ([]dts_parser.Statement, error) {
	decls, found := ownDecls(uri, classifications)
	if !found {
		return nil, fmt.Errorf("%s declares no exports and no `declare module %q` block", entry, uri)
	}
	for _, classification := range classifications {
		decls = append(decls, classification.GlobalDecls...)
	}
	return decls, nil
}

// ownDecls returns the declarations packageDecls calls the package's own, and reports
// whether the files hold any. The slice is a fresh copy the caller may append to.
func ownDecls(uri string, classifications []*dts_parser.FileClassification) ([]dts_parser.Statement, bool) {
	if classifications[0].HasTopLevelExports {
		decls := append([]dts_parser.Statement(nil), classifications[0].PackageDecls...)
		// The classifier holds `export as namespace N` apart from PackageDecls.
		if umd := classifications[0].ExportAsNamespace; umd != nil {
			decls = append(decls, umd)
		}
		return decls, true
	}
	var decls []dts_parser.Statement
	found := false
	for _, classification := range classifications {
		for _, named := range classification.NamedModules {
			if named.ModuleName == uri {
				decls = append(decls, named.Decls...)
				found = true
			}
		}
	}
	return decls, found
}
