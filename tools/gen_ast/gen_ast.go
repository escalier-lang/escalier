package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"strings"
	"text/template"

	"github.com/escalier-lang/escalier/internal/set"
)

func main() {
	if len(os.Args) < 3 {
		log.Fatal("Please provide path to gen_ast.go")
	}

	arg := os.Args[1]
	if !strings.HasPrefix(arg, "-p") {
		log.Fatalf("Expected argument to start with '-p', got: %s", arg)
	}
	inputPath := os.Args[2]
	outputPath := strings.Replace(inputPath, ".go", "_gen.go", 1)

	fmt.Fprintf(os.Stderr, "inputPath = %s\n", inputPath)
	fmt.Fprintf(os.Stderr, "outputPath = %s\n", outputPath)

	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, inputPath, nil, parser.ParseComments)
	if err != nil {
		log.Fatalf("Error parsing file: %v", err)
	}

	// A struct whose Span method the input file writes by hand keeps it, so
	// the generator skips it.
	handWritten := set.NewSet[string]()
	for _, decl := range node.Decls {
		funcDecl, ok := decl.(*ast.FuncDecl)
		if !ok || funcDecl.Recv == nil || funcDecl.Name.Name != "Span" {
			continue
		}
		if name, ok := receiverTypeName(funcDecl.Recv); ok {
			handWritten.Add(name)
		}
	}

	var typeStructs []string

	// Find every struct with a `span Span` field and no hand-written Span method.
	ast.Inspect(node, func(n ast.Node) bool {
		typeSpec, ok := n.(*ast.TypeSpec)
		if !ok {
			return true
		}

		structType, ok := typeSpec.Type.(*ast.StructType)
		if !ok {
			return true
		}

		if hasSpanField(structType) && !handWritten.Contains(typeSpec.Name.Name) {
			typeStructs = append(typeStructs, typeSpec.Name.Name)
		}

		return true
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tools/gen_ast/gen_ast.go; DO NOT EDIT.\n\n")
	buf.WriteString("package ast\n\n")

	tmpl := template.Must(template.New("span").Parse(`
func (node *{{.}}) Span() Span { return node.span }
`))

	for _, typeName := range typeStructs {
		err = tmpl.Execute(&buf, typeName)
		if err != nil {
			log.Fatalf("Error executing template: %v", err)
		}
	}

	// Format the generated code
	formattedCode, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("Error formatting code: %v", err)
	}

	// Write to file
	err = os.WriteFile(outputPath, formattedCode, 0644)
	if err != nil {
		log.Fatalf("Error writing file: %v", err)
	}

	fmt.Fprintf(os.Stderr, "Generated Span methods for %d types\n", len(typeStructs))
}

// hasSpanField reports whether a struct declares a field named `span` of type Span.
func hasSpanField(structType *ast.StructType) bool {
	for _, field := range structType.Fields.List {
		ident, ok := field.Type.(*ast.Ident)
		if !ok || ident.Name != "Span" {
			continue
		}
		for _, name := range field.Names {
			if name.Name == "span" {
				return true
			}
		}
	}
	return false
}

// receiverTypeName returns the type name a method's receiver names, with any
// pointer stripped.
func receiverTypeName(recv *ast.FieldList) (string, bool) {
	if len(recv.List) == 0 {
		return "", false
	}
	recvType := recv.List[0].Type
	if star, ok := recvType.(*ast.StarExpr); ok {
		recvType = star.X
	}
	ident, ok := recvType.(*ast.Ident)
	if !ok {
		return "", false
	}
	return ident.Name, true
}
